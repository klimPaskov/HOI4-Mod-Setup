    fn validate_lock(bytes: &[u8]) -> serde_json::Value {
        let lock: serde_json::Value = serde_json::from_slice(bytes).unwrap();
        let validator = crate::schemas::validator(include_str!(
            "../../../docs/schemas/installation-lock.schema.json"
        ))
        .unwrap();
        if let Err(error) = validator.validate(&lock) {
            panic!(
                "lock does not match the schema at {}: {error}",
                error.instance_path()
            );
        }
        lock
    }

    fn zip_file(archive: &[u8], path: &str) -> Option<Vec<u8>> {
        read_zip(archive)
            .unwrap()
            .into_iter()
            .find(|entry| entry.path == path)
            .map(|entry| entry.bytes)
    }

    #[test]
    fn existing_mods_are_compared_and_exported_as_an_overlay() {
        let fs = dropped();
        let files = incoming();
        let entries = plan_export(&files, Some(&fs)).unwrap();
        let action = |path: &str| {
            entries
                .iter()
                .find(|entry| entry.path == path)
                .unwrap()
                .action
        };
        assert_eq!(action("descriptor.mod"), ExportAction::Unchanged);
        assert_eq!(action("AGENTS.md"), ExportAction::Conflict);
        assert_eq!(action(".claude/skills/demo/SKILL.md"), ExportAction::Create);
        assert!(
            entries.iter().all(|entry| !entry.mergeable),
            "a first setup has no base to merge against"
        );

        let none = BTreeMap::new();
        let merged = BTreeMap::new();
        let undecided = build_export(request(
            &files,
            &entries,
            &none,
            &merged,
            Some(&fs),
            ExportLayout::Overlay,
        ));
        assert!(undecided.is_err(), "every conflict needs a decision");

        let decisions = BTreeMap::from([("AGENTS.md".to_owned(), Decision::Keep)]);
        let archive = build_export(request(
            &files,
            &entries,
            &decisions,
            &merged,
            Some(&fs),
            ExportLayout::Overlay,
        ))
        .unwrap();
        let paths = read_zip(&archive)
            .unwrap()
            .into_iter()
            .map(|entry| entry.path)
            .collect::<Vec<_>>();
        assert_eq!(
            paths,
            [
                ".claude/skills/demo/SKILL.md",
                ".hoi4-mod-setup/install.lock.json",
                "HOI4_MOD_SETUP_CHANGES.md"
            ],
            "an overlay holds only new files, the lock, and the change list"
        );
    }

    #[test]
    fn a_full_copy_keeps_every_local_file_and_the_lock_validates() {
        let mut fs = dropped();
        // A lock from an earlier export is replaced, never copied twice.
        fs.add_file(LOCK_PATH, b"{}".to_vec()).unwrap();
        let files = incoming();
        let entries = plan_export(&files, Some(&fs)).unwrap();
        let decisions = BTreeMap::from([("AGENTS.md".to_owned(), Decision::Keep)]);
        let merged = BTreeMap::new();
        let mut full = request(
            &files,
            &entries,
            &decisions,
            &merged,
            Some(&fs),
            ExportLayout::FullCopy,
        );
        full.root_files = vec![ZipEntry {
            path: "demo.mod".into(),
            bytes: b"name=\"Demo\"\npath=\"mod/demo\"\n".to_vec(),
        }];
        let archive = build_export(full).unwrap();
        assert_eq!(
            zip_file(&archive, "demo/AGENTS.md").unwrap(),
            b"# My own rules\n",
            "the kept file stays as it was"
        );
        assert_eq!(
            zip_file(&archive, "demo/events/demo.txt").unwrap(),
            b"add_namespace = demo\n"
        );
        assert_eq!(
            zip_file(&archive, "demo.mod").unwrap(),
            b"name=\"Demo\"\npath=\"mod/demo\"\n"
        );
        let lock =
            validate_lock(&zip_file(&archive, "demo/.hoi4-mod-setup/install.lock.json").unwrap());
        let agents = lock["files"]
            .as_array()
            .unwrap()
            .iter()
            .find(|file| file["path"] == "AGENTS.md")
            .unwrap();
        assert_eq!(agents["preserved_local"], true);
        assert_eq!(
            agents["installed_sha256"],
            sha256_bytes(b"# My own rules\n")
        );
    }

