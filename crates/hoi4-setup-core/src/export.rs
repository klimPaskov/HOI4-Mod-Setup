//! The web edition's result: compare the reviewed incoming files with the
//! folder the user dropped, apply the user's decisions, and write a ZIP with
//! the installation lock. Nothing is written into the dropped folder; it stays
//! the backup.
//!
//! A folder that already holds a setup is compared against its installation
//! lock as well, so maintenance follows the desktop rules: unchanged managed
//! files update or come back without a question, files the user changed are
//! reviewed, and managed files that are no longer selected are removed only
//! when the user never changed them.

use crate::adapters::{EntryKind, ProjectFs};
use crate::models::*;
use crate::text::{normalize_relative_path, sha256_bytes, validate_destination_set};
use crate::zip::{write_zip, ZipEntry};
use crate::AppError;
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};

/// Largest single project file compared or copied.
pub const MAX_EXPORT_FILE_BYTES: u64 = 64 * 1024 * 1024;

/// Where the installation lock lives in a project.
pub const LOCK_PATH: &str = ".hoi4-mod-setup/install.lock.json";

/// One reviewed file the setup wants in the project.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IncomingFile {
    pub path: String,
    pub component_id: String,
    pub bytes: Vec<u8>,
    pub ownership: Ownership,
    /// Manifest source path, or `generated:<path>` for generated files.
    pub source_path: String,
    /// SHA-256 and size of the verified source blob before adaptation; for a
    /// generated file, of the generated bytes. Maintenance fetches and checks
    /// the old source against this to rebuild a merge base.
    pub source_sha256: String,
    pub source_size: u64,
    pub executable: bool,
}

impl IncomingFile {
    fn generated(&self) -> bool {
        self.source_path.starts_with("generated:")
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ExportAction {
    /// The folder has no file here; the setup adds it.
    Create,
    /// The folder already has exactly these bytes.
    Unchanged,
    /// The folder has different bytes; the user decides.
    Conflict,
    /// A managed file the user never changed gets the new version.
    Update,
    /// A managed file is missing from the folder and comes back.
    Restore,
    /// A managed file the user never changed is no longer selected and is
    /// removed.
    Remove,
    /// A managed file is no longer selected but the user changed it, so it
    /// stays as the user's own file.
    Release,
    /// The user changed a managed file and the setup has no newer version,
    /// so the user's file stays without a question.
    Modified,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ExportEntry {
    pub path: String,
    pub component_id: String,
    pub action: ExportAction,
    /// The incoming bytes' hash; for a removed or released file, the hash the
    /// lock recorded.
    pub incoming_sha256: String,
    pub local_sha256: Option<String>,
    pub size: u64,
    /// A conflict on a managed text file whose installed version can be
    /// rebuilt as a three-way merge base.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub mergeable: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Decision {
    /// Keep the folder's file.
    Keep,
    /// Use the incoming file.
    Replace,
    /// Use the reviewed three-way merge.
    Merge,
    /// Keep the folder's file and add the incoming one beside it.
    Rename,
    /// Leave the file as it is and do not record the incoming version.
    Skip,
}

impl Decision {
    fn name(self) -> &'static str {
        match self {
            Decision::Keep => "keep",
            Decision::Replace => "replace",
            Decision::Merge => "merge",
            Decision::Rename => "rename",
            Decision::Skip => "skip",
        }
    }
}

/// What the ZIP holds for an existing mod.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ExportLayout {
    /// Only new and replaced files, to extract over the mod folder.
    Overlay,
    /// The whole mod folder with the changes applied.
    FullCopy,
}

fn exists(fs: &dyn ProjectFs, path: &str) -> Result<bool, AppError> {
    let parent = path.rsplit_once('/').map_or("", |(parent, _)| parent);
    if !parent.is_empty() && !exists_directory(fs, parent)? {
        return Ok(false);
    }
    Ok(fs
        .list(parent)?
        .iter()
        .any(|entry| entry.path == path && entry.kind == EntryKind::File))
}

fn exists_directory(fs: &dyn ProjectFs, path: &str) -> Result<bool, AppError> {
    let parent = path.rsplit_once('/').map_or("", |(parent, _)| parent);
    if !parent.is_empty() && !exists_directory(fs, parent)? {
        return Ok(false);
    }
    Ok(fs
        .list(parent)?
        .iter()
        .any(|entry| entry.path == path && entry.kind == EntryKind::Directory))
}

fn local_sha256(local: Option<&dyn ProjectFs>, path: &str) -> Result<Option<String>, AppError> {
    match local {
        Some(fs) if exists(fs, path)? => {
            Ok(Some(sha256_bytes(&fs.read(path, MAX_EXPORT_FILE_BYTES)?)))
        }
        _ => Ok(None),
    }
}

/// Whether a path holds text that a merge can combine.
pub fn mergeable_kind(path: &str) -> bool {
    let name = path.rsplit('/').next().unwrap_or(path).to_ascii_lowercase();
    !matches!(
        name.rsplit_once('.').map(|(_, extension)| extension),
        Some(
            "png"
                | "jpg"
                | "jpeg"
                | "webp"
                | "dds"
                | "tga"
                | "gif"
                | "bmp"
                | "ico"
                | "zip"
                | "exe"
                | "dll"
                | "so"
                | "dylib"
                | "wasm"
                | "ttf"
                | "otf"
                | "woff"
                | "woff2"
                | "pdf"
                | "mp3"
                | "ogg"
                | "wav"
                | "fbx"
                | "blend"
                | "glb"
        )
    )
}

/// Compare every incoming file with the dropped folder (`None` for a new mod).
pub fn plan_export(
    incoming: &[IncomingFile],
    local: Option<&dyn ProjectFs>,
) -> Result<Vec<ExportEntry>, AppError> {
    plan(incoming, local, None, &|_| true)
}

/// Compare a maintenance run with the folder and its installation lock.
/// `removable` says whether a managed file that is no longer selected may be
/// removed; project files such as the descriptor never are.
pub fn plan_maintenance(
    incoming: &[IncomingFile],
    local: &dyn ProjectFs,
    lock: &InstallationLock,
    removable: &dyn Fn(&LockedFile) -> bool,
) -> Result<Vec<ExportEntry>, AppError> {
    plan(incoming, Some(local), Some(lock), removable)
}

fn plan(
    incoming: &[IncomingFile],
    local: Option<&dyn ProjectFs>,
    lock: Option<&InstallationLock>,
    removable: &dyn Fn(&LockedFile) -> bool,
) -> Result<Vec<ExportEntry>, AppError> {
    let paths = incoming
        .iter()
        .map(|file| normalize_relative_path(&file.path))
        .collect::<Result<Vec<_>, _>>()?;
    validate_destination_set(&paths)?;
    let locked_files = lock
        .map(|lock| {
            lock.files
                .iter()
                .filter(|file| !file.external)
                .map(|file| Ok((normalize_relative_path(&file.path)?, file)))
                .collect::<Result<BTreeMap<_, _>, AppError>>()
        })
        .transpose()?
        .unwrap_or_default();
    let mut entries = Vec::with_capacity(incoming.len());
    for (file, path) in incoming.iter().zip(&paths) {
        let incoming_sha256 = sha256_bytes(&file.bytes);
        let local_sha256 = local_sha256(local, path)?;
        let locked = locked_files.get(path);
        let action = match (&local_sha256, locked) {
            (None, Some(_)) => ExportAction::Restore,
            (None, None) => ExportAction::Create,
            (Some(local), _) if *local == incoming_sha256 => ExportAction::Unchanged,
            (Some(local), Some(locked)) if *local == locked.installed_sha256 => {
                ExportAction::Update
            }
            (Some(_), Some(locked)) if locked.installed_sha256 == incoming_sha256 => {
                ExportAction::Modified
            }
            (Some(_), _) => ExportAction::Conflict,
        };
        let mergeable = action == ExportAction::Conflict
            && locked.is_some_and(|locked| {
                locked.ownership != Ownership::Merged
                    && !locked.preserved_local
                    && !locked.source_path.starts_with("generated:")
            })
            && mergeable_kind(path);
        entries.push(ExportEntry {
            path: path.clone(),
            component_id: file.component_id.clone(),
            action,
            incoming_sha256,
            local_sha256,
            size: file.bytes.len() as u64,
            mergeable,
        });
    }
    let wanted = paths.iter().cloned().collect::<BTreeSet<_>>();
    for (path, locked) in &locked_files {
        if wanted.contains(path) {
            continue;
        }
        let Some(local_sha256) = local_sha256(local, path)? else {
            continue;
        };
        let action = if local_sha256 == locked.installed_sha256 && removable(locked) {
            ExportAction::Remove
        } else {
            ExportAction::Release
        };
        entries.push(ExportEntry {
            path: path.clone(),
            component_id: locked.component_id.clone(),
            action,
            incoming_sha256: locked.installed_sha256.clone(),
            local_sha256: Some(local_sha256),
            size: locked.installed_size.unwrap_or_default(),
            mergeable: false,
        });
    }
    entries.sort_by(|left, right| left.path.cmp(&right.path));
    Ok(entries)
}

/// The non-file parts of the installation lock written into the ZIP.
#[derive(Debug, Clone)]
pub struct LockInputs {
    pub project_id: String,
    pub script_prefix: Option<String>,
    pub primary_namespace: Option<String>,
    pub installed_at: String,
    /// Set for maintenance; the first install keeps `installed_at`.
    pub updated_at: Option<String>,
    pub source: LockSourceIdentity,
    pub ai_provider: String,
    pub ai_model: String,
    pub ai_reasoning_effort: String,
    /// The hosted route address when a hosted provider made suggestions.
    pub ai_endpoint: Option<String>,
    pub ai_optimization_profile: String,
    pub primary_coding_environment: String,
    pub additional_coding_environments: Vec<String>,
    pub wiki_required_pages: Vec<String>,
    pub wiki_metadata: WikiInstallMetadata,
    pub components: Vec<LockComponent>,
    pub optional_workflows: BTreeMap<String, OptionalWorkflowLock>,
    pub portrait_pipeline: Option<PortraitPipelineConfig>,
    pub image_generation: Option<ImageGenerationSelection>,
    pub live_testing: Option<LiveTestingSelection>,
}

pub struct ExportRequest<'a> {
    pub incoming: &'a [IncomingFile],
    pub entries: &'a [ExportEntry],
    pub decisions: &'a BTreeMap<String, Decision>,
    /// Reviewed merge results for conflicts decided as `merge`.
    pub merged: &'a BTreeMap<String, Vec<u8>>,
    pub local: Option<&'a dyn ProjectFs>,
    pub layout: ExportLayout,
    /// Folder name for a full copy or a new mod, such as the project ID.
    pub root_folder: &'a str,
    /// Extra files placed at the archive root, such as the launcher
    /// descriptor `<id>.mod` for a new mod.
    pub root_files: Vec<ZipEntry>,
    pub lock: LockInputs,
    /// Managed removal: no lock is written and the old one is listed for
    /// deletion.
    pub remove_setup: bool,
}

fn locked_file(
    file: &IncomingFile,
    path: &str,
    revision: &str,
    installed: &[u8],
    preserved_local: bool,
    ownership: Ownership,
) -> LockedFile {
    let generated = file.generated() && !preserved_local;
    // Text is recorded once; only binary output keeps bytes.
    let generated_text = generated
        .then(|| String::from_utf8(installed.to_vec()).ok())
        .flatten();
    LockedFile {
        path: path.to_owned(),
        location_scope: Some("project".into()),
        component_id: file.component_id.clone(),
        source_path: file.source_path.clone(),
        source_revision: revision.to_owned(),
        source_sha256: file.source_sha256.clone(),
        source_size: Some(file.source_size),
        base_sha256: None,
        installed_sha256: sha256_bytes(installed),
        installed_size: Some(installed.len() as u64),
        ownership,
        preserved_local,
        external: false,
        generated_content: generated_text.clone(),
        generated_bytes: (generated && generated_text.is_none()).then(|| installed.to_vec()),
        executable: file.executable,
        platform: Some(ManifestPlatform::All),
        installer_created: !preserved_local && !file.generated(),
    }
}

/// The path an incoming file takes when the user keeps their own file:
/// `name.incoming.ext`, numbered when that is taken.
pub fn renamed_path(original: &str, taken: &dyn Fn(&str) -> bool) -> Result<String, AppError> {
    let (parent, name) = original
        .rsplit_once('/')
        .map_or(("", original), |(parent, name)| (parent, name));
    let (stem, extension) = match name.rsplit_once('.') {
        Some((stem, extension)) if !stem.is_empty() => (stem, format!(".{extension}")),
        _ => (name, String::new()),
    };
    for index in 0..1000 {
        let suffix = if index == 0 {
            ".incoming".to_owned()
        } else {
            format!(".incoming-{index}")
        };
        let candidate_name = format!("{stem}{suffix}{extension}");
        let candidate = if parent.is_empty() {
            candidate_name
        } else {
            format!("{parent}/{candidate_name}")
        };
        if !taken(&candidate) {
            return Ok(candidate);
        }
    }
    Err(AppError::InvalidInput(format!(
        "no free name is left beside {original}"
    )))
}

struct Summary<'a> {
    created: Vec<&'a str>,
    updated: Vec<&'a str>,
    restored: Vec<&'a str>,
    replaced: Vec<&'a str>,
    merged: Vec<&'a str>,
    renamed: Vec<(String, String)>,
    kept: Vec<&'a str>,
    removed: Vec<String>,
    released: Vec<&'a str>,
}

fn changes_summary(summary: &Summary<'_>) -> String {
    let list = |paths: &[&str]| {
        if paths.is_empty() {
            "- None\n".to_owned()
        } else {
            paths.iter().map(|path| format!("- `{path}`\n")).collect()
        }
    };
    let mut text = format!(
        "# Changes from HOI4 Mod Setup\n\nExtract this archive over your mod folder. Files not listed here are untouched.\n\n## Added\n\n{}\n",
        list(&summary.created)
    );
    for (title, paths) in [
        ("Updated", &summary.updated),
        ("Restored", &summary.restored),
        ("Replaced", &summary.replaced),
        ("Merged", &summary.merged),
    ] {
        if !paths.is_empty() {
            text.push_str(&format!("## {title}\n\n{}\n", list(paths)));
        }
    }
    if !summary.renamed.is_empty() {
        text.push_str("## Added beside your own file\n\n");
        for (original, renamed) in &summary.renamed {
            text.push_str(&format!("- `{renamed}` (yours stays at `{original}`)\n"));
        }
        text.push('\n');
    }
    text.push_str(&format!(
        "## Kept as you had them\n\n{}",
        list(&summary.kept)
    ));
    if !summary.removed.is_empty() {
        text.push_str("\n## Delete these files\n\nThe setup no longer uses them and you never changed them.\n\n");
        for path in &summary.removed {
            text.push_str(&format!("- `{path}`\n"));
        }
    }
    if !summary.released.is_empty() {
        text.push_str(&format!(
            "\n## No longer managed\n\nThe setup no longer uses these files, but you changed them, so they stay yours.\n\n{}",
            list(&summary.released)
        ));
    }
    text
}

/// Build the export ZIP. Every conflict needs a decision.
pub fn build_export(request: ExportRequest<'_>) -> Result<Vec<u8>, AppError> {
    let by_path = request
        .incoming
        .iter()
        .map(|file| Ok((normalize_relative_path(&file.path)?, file)))
        .collect::<Result<BTreeMap<_, _>, AppError>>()?;
    let revision = request.lock.source.revision.clone();
    let mut project_files: Vec<ZipEntry> = Vec::new();
    let mut locked = Vec::new();
    let mut summary = Summary {
        created: Vec::new(),
        updated: Vec::new(),
        restored: Vec::new(),
        replaced: Vec::new(),
        merged: Vec::new(),
        renamed: Vec::new(),
        kept: Vec::new(),
        removed: Vec::new(),
        released: Vec::new(),
    };
    // Paths the full copy must not take from the folder as they are.
    let mut skip_local = BTreeSet::new();
    let mut taken = by_path.keys().cloned().collect::<BTreeSet<_>>();
    let read_local = |path: &str| -> Result<Vec<u8>, AppError> {
        request
            .local
            .ok_or_else(|| AppError::InvalidInput("a kept file needs the dropped folder".into()))?
            .read(path, MAX_EXPORT_FILE_BYTES)
    };
    let mut choices = Vec::new();
    for entry in request.entries {
        if matches!(entry.action, ExportAction::Remove | ExportAction::Release) {
            if entry.action == ExportAction::Remove {
                skip_local.insert(entry.path.clone());
                summary.removed.push(entry.path.clone());
            } else {
                summary.released.push(&entry.path);
            }
            continue;
        }
        let file = by_path.get(&entry.path).ok_or_else(|| {
            AppError::InvalidInput(format!("the plan lists an unknown file: {}", entry.path))
        })?;
        let mut install = |bytes: &[u8], ownership: Ownership| {
            project_files.push(ZipEntry {
                path: entry.path.clone(),
                bytes: bytes.to_vec(),
            });
            skip_local.insert(entry.path.clone());
            locked.push(locked_file(
                file,
                &entry.path,
                &revision,
                bytes,
                false,
                ownership,
            ));
        };
        match entry.action {
            ExportAction::Create => {
                install(&file.bytes, file.ownership);
                summary.created.push(&entry.path);
            }
            ExportAction::Update => {
                install(&file.bytes, file.ownership);
                summary.updated.push(&entry.path);
            }
            ExportAction::Restore => {
                install(&file.bytes, file.ownership);
                summary.restored.push(&entry.path);
            }
            ExportAction::Modified => {
                // The lock keeps the installed version, so a later update can
                // still tell that the user changed the file.
                locked.push(locked_file(
                    file,
                    &entry.path,
                    &revision,
                    &file.bytes,
                    false,
                    file.ownership,
                ));
                summary.kept.push(&entry.path);
            }
            ExportAction::Unchanged => {
                if request.layout == ExportLayout::FullCopy || request.local.is_none() {
                    install(&file.bytes, file.ownership);
                } else {
                    locked.push(locked_file(
                        file,
                        &entry.path,
                        &revision,
                        &file.bytes,
                        false,
                        file.ownership,
                    ));
                }
            }
            ExportAction::Conflict => {
                let decision = request.decisions.get(&entry.path).copied().ok_or_else(|| {
                    AppError::InvalidInput(format!("decide what to do with {}", entry.path))
                })?;
                choices.push(MergeChoice {
                    path: entry.path.clone(),
                    choice: decision.name().into(),
                    result_sha256: None,
                });
                match decision {
                    Decision::Replace => {
                        install(&file.bytes, file.ownership);
                        summary.replaced.push(&entry.path);
                    }
                    Decision::Merge => {
                        let merged = request.merged.get(&entry.path).ok_or_else(|| {
                            AppError::InvalidInput(format!(
                                "review the merge of {} before exporting",
                                entry.path
                            ))
                        })?;
                        if let Some(choice) = choices.last_mut() {
                            choice.result_sha256 = Some(sha256_bytes(merged));
                        }
                        install(merged, Ownership::Merged);
                        summary.merged.push(&entry.path);
                    }
                    Decision::Keep => {
                        let local = read_local(&entry.path)?;
                        locked.push(locked_file(
                            file,
                            &entry.path,
                            &revision,
                            &local,
                            true,
                            file.ownership,
                        ));
                        summary.kept.push(&entry.path);
                    }
                    Decision::Skip => {
                        summary.kept.push(&entry.path);
                    }
                    Decision::Rename => {
                        let local_taken = |path: &str| {
                            taken.contains(path)
                                || request
                                    .local
                                    .is_some_and(|fs| exists(fs, path).unwrap_or(true))
                        };
                        let renamed = renamed_path(&entry.path, &local_taken)?;
                        taken.insert(renamed.clone());
                        project_files.push(ZipEntry {
                            path: renamed.clone(),
                            bytes: file.bytes.clone(),
                        });
                        locked.push(locked_file(
                            file,
                            &renamed,
                            &revision,
                            &file.bytes,
                            false,
                            file.ownership,
                        ));
                        summary.renamed.push((entry.path.clone(), renamed));
                    }
                }
            }
            ExportAction::Remove | ExportAction::Release => unreachable!("handled above"),
        }
    }
    if let (Some(fs), ExportLayout::FullCopy) = (request.local, request.layout) {
        let mut stack = vec![String::new()];
        while let Some(directory) = stack.pop() {
            for item in fs.list(&directory)? {
                match item.kind {
                    EntryKind::Directory => stack.push(item.path),
                    // The old lock is replaced or removed, never copied.
                    EntryKind::File
                        if !skip_local.contains(&item.path) && item.path != LOCK_PATH =>
                    {
                        project_files.push(ZipEntry {
                            bytes: fs.read(&item.path, MAX_EXPORT_FILE_BYTES)?,
                            path: item.path,
                        });
                    }
                    _ => {}
                }
            }
        }
    }
    locked.sort_by(|left, right| left.path.cmp(&right.path));
    let inputs = request.lock;
    if request.remove_setup {
        summary.removed.push(LOCK_PATH.into());
    } else {
        let lock = InstallationLock {
            schema_version: "1.0.0".into(),
            project_id: inputs.project_id,
            script_prefix: inputs.script_prefix,
            primary_namespace: inputs.primary_namespace,
            installed_at: inputs.installed_at,
            updated_at: inputs.updated_at,
            source: inputs.source,
            ai_provider: inputs.ai_provider,
            ai_model: inputs.ai_model,
            ai_reasoning_effort: inputs.ai_reasoning_effort,
            ai_endpoint: inputs.ai_endpoint,
            ai_optimization_profile: inputs.ai_optimization_profile,
            primary_coding_environment: inputs.primary_coding_environment,
            additional_coding_environments: inputs.additional_coding_environments,
            flatten_chat_sources: false,
            codex_analysis: None,
            wiki_required_pages: inputs.wiki_required_pages,
            wiki_metadata: Some(inputs.wiki_metadata),
            components: inputs.components,
            files: locked,
            merge_choices: choices,
            optional_workflows: inputs.optional_workflows,
            portrait_pipeline: inputs.portrait_pipeline,
            image_generation: inputs.image_generation,
            live_testing: inputs.live_testing,
            local_modifications: Vec::new(),
            rollback_records: Vec::new(),
        };
        project_files.push(ZipEntry {
            path: LOCK_PATH.into(),
            bytes: crate::text::persistable_json_bytes(&lock)?,
        });
    }
    if request.local.is_some() && request.layout == ExportLayout::Overlay {
        project_files.push(ZipEntry {
            path: "HOI4_MOD_SETUP_CHANGES.md".into(),
            bytes: changes_summary(&summary).into_bytes(),
        });
    }
    let prefix = if request.local.is_some() && request.layout == ExportLayout::Overlay {
        String::new()
    } else {
        format!("{}/", normalize_relative_path(request.root_folder)?)
    };
    let mut archive_entries = request.root_files;
    archive_entries.extend(project_files.into_iter().map(|file| ZipEntry {
        path: format!("{prefix}{}", file.path),
        bytes: file.bytes,
    }));
    archive_entries.sort_by(|left, right| left.path.cmp(&right.path));
    write_zip(&archive_entries)
}

