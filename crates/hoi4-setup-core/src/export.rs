    #[test]
    fn maintenance_updates_restores_and_removes_only_untouched_managed_files() {
        let mut fs = MemoryFs::new();
        fs.add_file("skills/a.md", b"a v1".to_vec()).unwrap();
        fs.add_file("skills/b.md", b"b changed by me".to_vec())
            .unwrap();
        fs.add_file("skills/old.md", b"old v1".to_vec()).unwrap();
        fs.add_file("skills/old-mine.md", b"old edited".to_vec())
            .unwrap();
        fs.add_file("skills/d.md", b"d edited".to_vec()).unwrap();
        fs.add_file("descriptor.mod", b"name=\"Demo\"\n".to_vec())
            .unwrap();
        let lock = installed_lock(vec![
            installed("skills/a.md", "core.skills", b"a v1", Ownership::Managed),
            installed("skills/b.md", "core.skills", b"b v1", Ownership::Managed),
            installed("skills/c.md", "core.skills", b"c v1", Ownership::Managed),
            installed("skills/d.md", "core.skills", b"d v1", Ownership::Managed),
            installed(
                "skills/old.md",
                "runtime.codex.skills",
                b"old v1",
                Ownership::Managed,
            ),
            installed(
                "skills/old-mine.md",
                "runtime.codex.skills",
                b"old v1",
                Ownership::Managed,
            ),
            installed(
                "descriptor.mod",
                "project.descriptor",
                b"name=\"Demo\"\n",
                Ownership::Generated,
            ),
        ]);
        let files = vec![
            managed("skills/a.md", b"a v2"),
            managed("skills/b.md", b"b v2"),
            managed("skills/c.md", b"c v1"),
            managed("skills/d.md", b"d v1"),
        ];
        let removable = |file: &LockedFile| !file.component_id.starts_with("project.");
        let entries = plan_maintenance(&files, &fs, &lock, &removable).unwrap();
        let action = |path: &str| entries.iter().find(|entry| entry.path == path).unwrap();
        assert_eq!(action("skills/a.md").action, ExportAction::Update);
        assert_eq!(action("skills/b.md").action, ExportAction::Conflict);
        assert!(
            action("skills/b.md").mergeable,
            "a managed text file can merge"
        );
        assert_eq!(action("skills/c.md").action, ExportAction::Restore);
        assert_eq!(
            action("skills/d.md").action,
            ExportAction::Modified,
            "a change with no newer version is kept without a question"
        );
        assert_eq!(action("skills/old.md").action, ExportAction::Remove);
        assert_eq!(action("skills/old-mine.md").action, ExportAction::Release);
        assert_eq!(
            action("descriptor.mod").action,
            ExportAction::Release,
            "project files are never removed"
        );

        let decisions = BTreeMap::from([("skills/b.md".to_owned(), Decision::Merge)]);
        let merged = BTreeMap::from([("skills/b.md".to_owned(), b"b v2 with my change".to_vec())]);
        let mut overlay = request(
            &files,
            &entries,
            &decisions,
            &merged,
            Some(&fs),
            ExportLayout::Overlay,
        );
        overlay.lock.updated_at = Some("2026-10-19T00:00:00Z".into());
        let archive = build_export(overlay).unwrap();
        assert_eq!(zip_file(&archive, "skills/a.md").unwrap(), b"a v2");
        assert_eq!(
            zip_file(&archive, "skills/b.md").unwrap(),
            b"b v2 with my change"
        );
        assert_eq!(zip_file(&archive, "skills/c.md").unwrap(), b"c v1");
        assert!(zip_file(&archive, "skills/old.md").is_none());
        let changes =
            String::from_utf8(zip_file(&archive, "HOI4_MOD_SETUP_CHANGES.md").unwrap()).unwrap();
        assert!(changes.contains("## Delete these files") && changes.contains("`skills/old.md`"));
        assert!(
            changes.contains("## No longer managed") && changes.contains("`skills/old-mine.md`")
        );
        let lock = validate_lock(&zip_file(&archive, LOCK_PATH).unwrap());
        let paths = lock["files"]
            .as_array()
            .unwrap()
            .iter()
            .map(|file| file["path"].as_str().unwrap().to_owned())
            .collect::<Vec<_>>();
        assert_eq!(
            paths,
            ["skills/a.md", "skills/b.md", "skills/c.md", "skills/d.md"]
        );
        assert!(
            zip_file(&archive, "skills/d.md").is_none(),
            "the user's file is left alone"
        );
        assert_eq!(lock["updated_at"], "2026-10-19T00:00:00Z");
        let merged_file = &lock["files"][1];
        assert_eq!(merged_file["ownership"], "merged");
        assert_eq!(lock["merge_choices"][0]["choice"], "merge");

        // A merge decision without a reviewed result is refused.
        let missing = BTreeMap::new();
        assert!(build_export(request(
            &files,
            &entries,
            &decisions,
            &missing,
            Some(&fs),
            ExportLayout::Overlay
        ))
        .is_err());
    }

